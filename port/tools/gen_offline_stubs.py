"""Generate src/hle/offline_stubs.cpp: constant-return stubs for services the port runs
without (PSN, networking, system dialogs, capture). Functions already implemented natively
(any HLE_EXPORT / FN / HLE_CONSTANT name in src/hle) are skipped.

Usage: py -I gen_offline_stubs.py <docs/imports.tsv> <port/src/hle>
"""
import pathlib
import re
import sys

LIBRARIES = re.compile(
    r"^libSce(Np\w*|Net|NetCtl|Http|Ssl|\w*Dialog|Coredump|ScreenShot|Remoteplay|"
    r"VideoRecording|GameLiveStreaming|NpTrophy)$")

# Calls that set up, tear down or configure succeed; everything else reports "offline".
SUCCEEDS = re.compile(
    r"^sce\w*?(Initialize|Init|Term|Terminate|Shutdown|Register\w*|Unregister\w*|Set\w*|"
    r"Check\w*|Delete\w*|Destroy\w*|Abort\w*|Close|Prohibit|Enable|Disable|Permit\w*|"
    r"Prepare|PoolCreate|PoolDestroy|ContextStart|ContextStop|WriteUserData)$")

OFFLINE_ERROR = {
    "Np": 0x80550006,        # SCE_NP_ERROR_SIGNED_OUT
    "NetCtl": 0x80412108,    # SCE_NET_CTL_ERROR_NOT_CONNECTED
    "Net": 0x80410132,       # ENETDOWN
    "Http": 0x80431001,
    "Ssl": 0x80431001,
    "Dialog": 0x80ED0002,    # dialog not available
}
DIALOG_FINISHED = 3          # UpdateStatus: SCE_COMMON_DIALOG_STATUS_FINISHED


def error_for(lib):
    name = lib[len("libSce"):]
    if name.endswith("Dialog"):
        return OFFLINE_ERROR["Dialog"]
    for key in ("NetCtl", "Net", "Http", "Ssl", "Np"):
        if name.startswith(key):
            return OFFLINE_ERROR[key]
    return 0


def main(tsv, hle_dir):
    implemented = set()
    for src in pathlib.Path(hle_dir).glob("*.cpp"):
        if src.name == "offline_stubs.cpp":
            continue
        implemented |= set(re.findall(r'"(sce\w+)"', src.read_text(encoding="utf-8")))

    lines = []
    for row in open(tsv, encoding="utf-8").read().splitlines()[1:]:
        lib, sym, _nid, _uses = row.split("\t")
        if not LIBRARIES.match(lib) or sym in implemented:
            continue
        if sym.endswith("UpdateStatus"):
            ret = DIALOG_FINISHED
        elif SUCCEEDS.match(sym):
            ret = 0
        else:
            ret = error_for(lib)
        lines.append(f'HLE_CONSTANT("{lib}", "{sym}", {ret:#x});')

    out = pathlib.Path(hle_dir) / "offline_stubs.cpp"
    out.write_text(
        "// Generated by port/tools/gen_offline_stubs.py; do not edit.\n"
        "// Services the port runs without: calls that set up or configure succeed, others report offline.\n"
        '#include "hle/hle.h"\n\n' + "\n".join(lines) + "\n",
        encoding="utf-8")
    print(f"{len(lines)} offline stubs")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
